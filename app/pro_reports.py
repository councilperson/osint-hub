"""Professional Report Service.

Generates branded PDF/DOCX reports from scan results with custom templates.
Supports:
  - Custom logo, colors, cover page
  - Executive summary auto-generation
  - Methodology section
  - Appendix with raw data
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from xml.sax.saxutils import escape

from . import db


# Default template
DEFAULT_TEMPLATE = {
    "branding": {
        "logo_path": "",
        "primary_color": "#3fb950",
        "secondary_color": "#0c0c0e",
        "font_family": "Inter, system-ui, sans-serif",
    },
    "cover_page": {
        "title": "OSINT Intelligence Report",
        "subtitle": "Automated Open Source Intelligence Analysis",
        "show_logo": True,
        "show_date": True,
        "show_classification": True,
        "classification": "CONFIDENTIAL",
    },
    "sections": {
        "executive_summary": True,
        "methodology": True,
        "findings": True,
        "appendix": False,
    },
    "footer": {
        "text": "Generated by OSINT Hub — {date}",
        "show_page_numbers": True,
    },
}


def _merge(default: dict, custom) -> dict:
    """Overlay a user's template on the default, section by section.

    Unknown keys are dropped and values are coerced to the default's type, so
    a hand-edited template can never crash report generation."""
    out: dict = {}
    custom = custom if isinstance(custom, dict) else {}
    for key, base in default.items():
        val = custom.get(key, base)
        if isinstance(base, dict):
            out[key] = _merge(base, val)
        elif isinstance(base, bool):
            out[key] = bool(val)
        elif isinstance(base, str):
            out[key] = str(val)[:300] if val is not None else base
        else:
            out[key] = val
    return out


def _load_template(user_id: int, template_id: int | None) -> dict:
    """Load a report template, falling back to default."""
    if template_id:
        t = db.get_report_template(template_id, user_id)
        if t:
            raw = t["template_json"]
            if isinstance(raw, str):
                try:
                    raw = json.loads(raw or "{}")
                except ValueError:
                    raw = {}
            return _merge(DEFAULT_TEMPLATE, raw)
    return _merge(DEFAULT_TEMPLATE, {})


def safe_filename(query: str, ext: str) -> str:
    """An ASCII-only, header-safe download name."""
    import re as _re
    stem = _re.sub(r"[^A-Za-z0-9._-]+", "_", str(query or "scan"))[:60].strip("._") or "scan"
    return f"osint-report-{stem}-{datetime.now().strftime('%Y%m%d')}.{ext}"


def _build_executive_summary(scan: dict, hits: list[dict]) -> str:
    """Auto-generate executive summary from scan results."""
    total_hits = len(hits)
    categories = {}
    for h in hits:
        cat = h.get("category", "unknown")
        categories[cat] = categories.get(cat, 0) + 1

    top_cats = sorted(categories.items(), key=lambda x: x[1], reverse=True)[:5]

    summary = f"""
    This report presents the results of an OSINT scan performed on <strong>{escape(scan.get('query', 'N/A'))}</strong>
    (resolved value: <strong>{escape(scan.get('value', 'N/A'))}</strong>) on {scan.get('created_str', 'N/A')}.

    The scan checked <strong>{scan.get('checked', 0)}</strong> endpoints across <strong>{scan.get('total', 0)}</strong>
    total sources and completed in <strong>{float(scan.get('elapsed', 0)):.2f}</strong> seconds.

    <strong>{total_hits}</strong> matches were found across the following top categories:
    """
    if top_cats:
        summary += "<ul>"
        for cat, count in top_cats:
            summary += f"<li>{escape(cat)}: {count} matches</li>"
        summary += "</ul>"
    else:
        summary += "<p>No matches found.</p>"

    summary += """
    <p><strong>Key Findings:</strong></p>
    <ul>
    """
    for h in hits[:5]:
        summary += f"<li><strong>{escape(h.get('name', 'Unknown'))}</strong> ({escape(h.get('category', 'unknown'))}): {escape(h.get('detail', '')[:200])}</li>"
    if len(hits) > 5:
        summary += f"<li>...and {len(hits) - 5} more matches</li>"
    summary += "</ul>"

    return summary


def _build_methodology() -> str:
    return """
    <h3>Data Collection</h3>
    <p>This scan was performed using OSINT Hub's automated intelligence engine, which queries public
    endpoints across multiple categories including social media, developer platforms, gaming networks,
    e-commerce sites, and long-tail forums/wikis. Each endpoint is queried via standard HTTP GET requests
    with no authentication, scraping, or access to private data.</p>

    <h3>Result Classification</h3>
    <p>Each endpoint returns one of three classifications:</p>
    <ul>
        <li><strong>Hit</strong> — The endpoint returned a positive match (profile exists, account active).</li>
        <li><strong>Miss</strong> — The endpoint explicitly indicated no match (404, 'user not found', etc.).</li>
        <li><strong>Unresolved</strong> — The endpoint could not be definitively classified (rate limited, blocked, timeout).</li>
    </ul>
    <p>Only <strong>Hit</strong> results are included in the findings section. Unresolved endpoints are not
    counted as matches and should be investigated manually if required.</p>

    <h3>Limitations</h3>
    <ul>
        <li>Results reflect the state of public sources at scan time; accounts may be created/deleted after the scan.</li>
        <li>Some platforms employ anti-bot measures that may cause false negatives (unresolved).</li>
        <li>This tool does not access private data, authenticate to platforms, or bypass access controls.</li>
    </ul>
    """


def generate_professional_report(
    scan: dict,
    template: dict,
    format: str = "pdf"
) -> tuple[bytes, str]:
    """
    Generate a professional branded report.

    Returns: (file_bytes, filename)
    """
    hits = [h for h in (scan.get("results") or []) if h.get("status") == "hit"]
    branding = template.get("branding", {})
    cover = template.get("cover_page", {})
    sections = template.get("sections", {})
    footer = template.get("footer", {})

    if format == "pdf":
        return _generate_pdf_report(scan, hits, branding, cover, sections, footer)
    elif format == "docx":
        return _generate_docx_report(scan, hits, branding, cover, sections, footer)
    else:
        raise ValueError(f"Unsupported format: {format}")


def _generate_pdf_report(
    scan: dict,
    hits: list[dict],
    branding: dict,
    cover: dict,
    sections: dict,
    footer: dict
) -> tuple[bytes, str]:
    """Generate professional PDF report using stdlib only."""
    primary = branding.get("primary_color", "#3fb950")
    secondary = branding.get("secondary_color", "#0c0c0e")

    # Use the existing PDF generator but with custom content
    # We'll build a richer PDF manually
    from .reports import _Pdf, _ascii, PAGE_W, PAGE_H, MARGIN_X, MARGIN_TOP, LEADING

    pdf = _Pdf()

    # --- Cover Page ---
    pdf.text(MARGIN_X, MARGIN_TOP, "OSINT HUB", 10, "F2", 0.5)
    pdf.text(MARGIN_X, MARGIN_TOP - 30, cover.get("title", "Intelligence Report"), 28, "F2")
    if cover.get("subtitle"):
        pdf.text(MARGIN_X, MARGIN_TOP - 65, cover["subtitle"], 14, "F1", 0.3)

    if cover.get("show_date"):
        pdf.text(MARGIN_X, MARGIN_TOP - 100, f"Date: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", 11, "F1", 0.4)

    if cover.get("show_classification"):
        cls = cover.get("classification", "CONFIDENTIAL")
        pdf.text(MARGIN_X, MARGIN_TOP - 130, f"Classification: {cls}", 12, "F2", 0.5)

    pdf.line(MARGIN_X, MARGIN_TOP - 150, PAGE_W - MARGIN_X, MARGIN_TOP - 150, 0.6)

    # Target info
    y = MARGIN_TOP - 180
    pdf.text(MARGIN_X, y, "TARGET INFORMATION", 10, "F2", 0.4)
    y -= 20
    info = [
        ("Query", str(scan.get("query", "N/A"))),
        ("Resolved Value", str(scan.get("value", "N/A"))),
        ("Search Type", str(scan.get("kind", "N/A")).upper()),
        ("Scan Date", scan.get("created_str", "N/A")),
        ("Duration", f"{float(scan.get('elapsed', 0)):.2f} seconds"),
        ("Endpoints Checked", f"{scan.get('checked', 0)} of {scan.get('total', 0)}"),
        ("Matches Found", str(scan.get("found", 0))),
    ]
    for label, value in info:
        pdf.text(MARGIN_X, y, _ascii(label), 9, "F2", 0.4)
        pdf.text(MARGIN_X + 130, y, _ascii(value), 10, "F1")
        y -= 16

    pdf.new_page()

    # --- Table of Contents ---
    pdf.text(MARGIN_X, MARGIN_TOP, "TABLE OF CONTENTS", 18, "F2")
    y = MARGIN_TOP - 40
    toc = [
        ("1.", "Executive Summary"),
        ("2.", "Methodology"),
        ("3.", "Findings"),
    ]
    if sections.get("appendix"):
        toc.append(("4.", "Appendix: Raw Data"))
    for num, title in toc:
        pdf.text(MARGIN_X, y, _ascii(f"{num} {title}"), 12, "F1")
        y -= 20

    pdf.new_page()

    # --- Executive Summary ---
    if sections.get("executive_summary"):
        pdf.text(MARGIN_X, MARGIN_TOP, "1. EXECUTIVE SUMMARY", 18, "F2")
        y = MARGIN_TOP - 40
        summary = _build_executive_summary(scan, hits)
        # Simple text rendering (HTML not supported in stdlib PDF)
        for line in summary.split("\n"):
            line = _ascii(line.strip())
            if line:
                pdf.text(MARGIN_X, y, line, 10, "F1")
                y -= LEADING
                if y < 60:
                    pdf.new_page()
                    y = MARGIN_TOP

    pdf.new_page()

    # --- Methodology ---
    if sections.get("methodology"):
        pdf.text(MARGIN_X, MARGIN_TOP, "2. METHODOLOGY", 18, "F2")
        y = MARGIN_TOP - 40
        for line in _build_methodology().split("\n"):
            line = _ascii(line.strip())
            if line:
                if line.startswith("<h3>"):
                    line = line[4:-5]
                    pdf.text(MARGIN_X, y, line, 12, "F2")
                elif line.startswith("<li>"):
                    line = "  • " + line[4:-5]
                    pdf.text(MARGIN_X + 10, y, line, 10, "F1")
                elif line.startswith("<p>"):
                    line = line[3:-4]
                    pdf.text(MARGIN_X, y, line, 10, "F1")
                else:
                    pdf.text(MARGIN_X, y, line, 10, "F1")
                y -= LEADING
                if y < 60:
                    pdf.new_page()
                    y = MARGIN_TOP

    pdf.new_page()

    # --- Findings ---
    if sections.get("findings"):
        pdf.text(MARGIN_X, MARGIN_TOP, "3. FINDINGS", 18, "F2")
        pdf.text(MARGIN_X, MARGIN_TOP - 30, f"Total Matches: {len([h for h in (scan.get('results') or []) if h.get('status') == 'hit'])}", 11, "F1", 0.4)
        y = MARGIN_TOP - 50

        for i, h in enumerate([h for h in (scan.get("results") or []) if h.get("status") == "hit"], 1):
            if y < 140:
                pdf.new_page()
                y = MARGIN_TOP
            pdf.text(MARGIN_X, y, f"{i}. {_ascii(h.get('name', 'Unknown'))}", 12, "F2")
            y -= 16
            pdf.text(MARGIN_X + 10, y, f"Category: {_ascii(h.get('category', 'unknown'))}", 10, "F1", 0.4)
            y -= 14
            pdf.text(MARGIN_X + 10, y, f"URL: {_ascii(h.get('url', ''))}", 9, "F3", 0.3)
            y -= 14
            if h.get("detail"):
                pdf.text(MARGIN_X + 10, y, f"Detail: {_ascii(h['detail'][:300])}", 9, "F1", 0.35)
                y -= 14
            if h.get("display_name"):
                pdf.text(MARGIN_X + 10, y, f"Display Name: {_ascii(h['display_name'])}", 9, "F1", 0.35)
                y -= 14
            if h.get("meta"):
                meta_str = " | ".join(f"{k}: {v}" for k, v in h["meta"][:5])
                pdf.text(MARGIN_X + 10, y, f"Metadata: {_ascii(meta_str)}", 8, "F1", 0.3)
                y -= 14
            y -= 10

    # --- Appendix ---
    if sections.get("appendix"):
        pdf.new_page()
        pdf.text(MARGIN_X, MARGIN_TOP, "APPENDIX: RAW SCAN DATA", 18, "F2")
        y = MARGIN_TOP - 40
        all_results = scan.get("results") or []
        for h in all_results:
            if y < 80:
                pdf.new_page()
                y = MARGIN_TOP
            status = h.get("status", "unknown")
            pdf.text(MARGIN_X, y, f"[{status.upper()}] {_ascii(h.get('name', ''))} ({_ascii(h.get('category', ''))})", 9, "F1")
            y -= 12
            pdf.text(MARGIN_X + 10, y, _ascii(h.get('url', '')), 8, "F3", 0.3)
            y -= 12

    # Build PDF
    data = pdf.build()
    filename = safe_filename(scan.get("query", "scan"), "pdf")
    return data, filename


def _generate_docx_report(
    scan: dict,
    hits: list[dict],
    branding: dict,
    cover: dict,
    sections: dict,
    footer: dict
) -> tuple[bytes, str]:
    """Generate professional DOCX report using stdlib only."""
    import io
    import zipfile

    # Build document XML
    body_parts = []

    # Helper
    def p(text: str, style: str = "", bold: bool = False) -> str:
        style_attr = f'<w:pPr><w:pStyle w:val="{style}"/></w:pPr>' if style else ""
        run_bold = "<w:b/>" if bold else ""
        return f'<w:p>{style_attr}<w:r><w:rPr>{run_bold}</w:rPr><w:t xml:space="preserve">{escape(text)}</w:t></w:r></w:p>'

    # Cover page
    if cover.get("title"):
        body_parts.append(p(cover["title"], "Title", True))
    if cover.get("subtitle"):
        body_parts.append(p(cover["subtitle"], "Heading1"))
    if cover.get("show_date"):
        body_parts.append(p(f"Date: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", "Small"))
    body_parts.append(p(""))

    # Target info
    body_parts.append(p("TARGET INFORMATION", "Heading1"))
    info = [
        ("Query", str(scan.get("query", "N/A"))),
        ("Resolved Value", str(scan.get("value", "N/A"))),
        ("Search Type", str(scan.get("kind", "N/A")).upper()),
        ("Scan Date", scan.get("created_str", "N/A")),
        ("Duration", f"{float(scan.get('elapsed', 0)):.2f} seconds"),
        ("Endpoints Checked", f"{scan.get('checked', 0)} of {scan.get('total', 0)}"),
        ("Matches Found", str(scan.get("found", 0))),
    ]
    for label, value in info:
        body_parts.append(p(f"{label}: {value}", "Small"))
    body_parts.append(p(""))

    # Executive Summary
    if sections.get("executive_summary"):
        body_parts.append(p("EXECUTIVE SUMMARY", "Heading1"))
        body_parts.append(p(_build_executive_summary(scan, [h for h in (scan.get("results") or []) if h.get("status") == "hit"]).replace("<p>", "").replace("</p>", "\n").replace("<strong>", "").replace("</strong>", "").replace("<ul>", "").replace("</ul>", "").replace("<li>", "• ").replace("</li>", "\n"), "Small"))
        body_parts.append(p(""))

    # Methodology
    if sections.get("methodology"):
        body_parts.append(p("METHODOLOGY", "Heading1"))
        body_parts.append(p(_build_methodology().replace("<h3>", "").replace("</h3>", "").replace("<p>", "").replace("</p>", "\n").replace("<ul>", "").replace("</ul>", "").replace("<li>", "• ").replace("</li>", "\n"), "Small"))
        body_parts.append(p(""))

    # Findings
    if sections.get("findings"):
        body_parts.append(p("FINDINGS", "Heading1"))
        body_parts.append(p(f"Total Matches: {len([h for h in (scan.get('results') or []) if h.get('status') == 'hit'])}", "Small"))
        body_parts.append(p(""))
        for i, h in enumerate([h for h in (scan.get("results") or []) if h.get("status") == "hit"], 1):
            body_parts.append(p(f"{i}. {h.get('name', 'Unknown')}", "", True))
            body_parts.append(p(f"  Category: {h.get('category', 'unknown')}", "Small"))
            body_parts.append(p(f"  URL: {h.get('url', '')}", "Mono"))
            if h.get("detail"):
                body_parts.append(p(f"  Detail: {h['detail']}", "Small"))
            if h.get("display_name"):
                body_parts.append(p(f"  Display Name: {h['display_name']}", "Small"))
            if h.get("meta"):
                meta_str = "; ".join(f"{k}: {v}" for k, v in h["meta"])
                body_parts.append(p(f"  Metadata: {meta_str}", "Small"))
            body_parts.append(p(""))

    # Appendix
    if sections.get("appendix"):
        body_parts.append(p("APPENDIX: RAW SCAN DATA", "Heading1"))
        for h in scan.get("results") or []:
            body_parts.append(p(f"[{h.get('status', 'unknown').upper()}] {h.get('name', '')} ({h.get('category', '')})", "Mono"))
            body_parts.append(p(f"  {h.get('url', '')}", "Mono"))

    # Build DOCX
    document = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        '<w:body>' + "".join(body_parts) +
        '<w:sectPr><w:pgSz w:w="11906" w:h="16838"/>'
        '<w:pgMar w:top="1134" w:right="1134" w:bottom="1134" w:left="1134"/>'
        '</w:sectPr></w:body></w:document>'
    )

    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    core = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/">'
        '<dc:title>OSINT Professional Report</dc:title>'
        f'<dc:creator>OSINT Hub</dc:creator>'
        f'<dcterms:created xsi:type="dcterms:W3CDTF" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">{now}</dcterms:created>'
        '</cp:coreProperties>'
    )

    content_types = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
        '<Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>'
        '<Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>'
        '<Override PartName="/docProps/app.xml" ContentType="application/vnd.openxmlformats-officedocument.extended-properties+xml"/>'
        '</Types>'
    )

    rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>'
        '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/>'
        '<Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/extended-properties" Target="docProps/app.xml"/>'
        '</Relationships>'
    )

    doc_rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>'
        '</Relationships>'
    )

    styles = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<w:styles xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        '<w:style w:type="paragraph" w:styleId="Title"><w:name w:val="Title"/><w:pPr><w:spacing w:before="0" w:after="120"/></w:pPr><w:rPr><w:b/><w:sz w:val="40"/></w:rPr></w:style>'
        '<w:style w:type="paragraph" w:styleId="Heading1"><w:name w:val="heading 1"/><w:pPr><w:spacing w:before="240" w:after="80"/></w:pPr><w:rPr><w:b/><w:sz w:val="26"/></w:rPr></w:style>'
        '<w:style w:type="paragraph" w:styleId="Mono"><w:name w:val="Mono"/><w:rPr><w:rFonts w:ascii="Consolas" w:hAnsi="Consolas"/><w:sz w:val="17"/></w:rPr></w:style>'
        '<w:style w:type="paragraph" w:styleId="Small"><w:name w:val="Small"/><w:rPr><w:sz w:val="17"/><w:color w:val="666666"/></w:rPr></w:style>'
        '</w:styles>'
    )

    app = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties">'
        '<Application>OSINT Hub</Application></Properties>'
    )

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", content_types)
        z.writestr("_rels/.rels", rels)
        z.writestr("docProps/core.xml", core)
        z.writestr("docProps/app.xml", app)
        z.writestr("word/document.xml", document)
        z.writestr("word/styles.xml", styles)
        z.writestr("word/_rels/document.xml.rels", doc_rels)

    filename = safe_filename(scan.get("query", "scan"), "docx")
    return buf.getvalue(), filename
